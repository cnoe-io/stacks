#!/usr/bin/env bash
#
# generate-nginx-override.sh - Generate nginx override with embedded persistent TLS certificate
#
# This script:
#   1. Reads the static Deployment from git (version-controlled, no secrets)
#   2. Fetches TLS certificate from Azure Key Vault
#   3. Combines them into a single YAML file for idpbuilder -c nginx:
#
# Architecture:
#   - Static Deployment: deployment/overrides/nginx-hostnetwork-no-hostport.yaml (in git)
#   - Dynamic Secret: Generated from Azure Key Vault at runtime
#   - ExternalSecret: packages/base/manifests/nginx-tls-secret/ manages ongoing updates
#
# Usage:
#   ./generate-nginx-override.sh [--output PATH]
#
# Output:
#   Default: /tmp/nginx-override-with-cert.yaml
#
# Environment:
#   AZURE_KEYVAULT_NAME - Key Vault name (default: keyvault-thcmfmoo5oeow)
#   STACKS_DIR - Path to stacks repository
#

set -euo pipefail

# Configuration
VAULT_NAME="${AZURE_KEYVAULT_NAME:-keyvault-thcmfmoo5oeow}"
OUTPUT_FILE="${1:-/tmp/nginx-override-with-cert.yaml}"
STACKS_DIR="${STACKS_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)}"
# Static Deployment file - version controlled in git, no secrets
NGINX_DEPLOYMENT="$STACKS_DIR/deployment/overrides/nginx-hostnetwork-no-hostport.yaml"

# Colors
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
BLUE='\033[0;34m'
NC='\033[0m'

log_info() { echo -e "${BLUE}i${NC} $*" >&2; }
log_success() { echo -e "${GREEN}✓${NC} $*" >&2; }
log_warning() { echo -e "${YELLOW}⚠${NC} $*" >&2; }
log_error() { echo -e "${RED}✖${NC} $*" >&2; }

# Parse arguments
while [[ $# -gt 0 ]]; do
    case "$1" in
        --output)
            OUTPUT_FILE="$2"
            shift 2
            ;;
        --help|-h)
            echo "Usage: $0 [--output PATH]"
            echo ""
            echo "Generates nginx override YAML with embedded TLS certificate from Azure Key Vault."
            echo ""
            echo "Options:"
            echo "  --output PATH    Output file path (default: /tmp/nginx-override-with-cert.yaml)"
            exit 0
            ;;
        *)
            # If not a flag, assume it's the output path
            if [[ ! "$1" =~ ^- ]]; then
                OUTPUT_FILE="$1"
            fi
            shift
            ;;
    esac
done

# Check prerequisites
command -v az &>/dev/null || { log_error "Azure CLI (az) not found"; exit 1; }

# Check if persistent secrets exist in Key Vault
log_info "Checking for persistent TLS certificate in Azure Key Vault..."

if ! az keyvault secret show --vault-name "$VAULT_NAME" --name "IDPBUILDER-TLS-CRT" &>/dev/null; then
    log_warning "Persistent TLS certificate not found in Key Vault"
    log_warning "Run setup-persistent-certs.sh first to generate and upload certificates"
    log_info "Falling back to standard nginx deployment without embedded certificate"

    # Fall back to just copying the static deployment (idpbuilder will generate its own cert)
    if [ -f "$NGINX_DEPLOYMENT" ]; then
        cp "$NGINX_DEPLOYMENT" "$OUTPUT_FILE"
        log_info "Using standard nginx deployment: $OUTPUT_FILE"
        echo "$OUTPUT_FILE"
        exit 0
    else
        log_error "Nginx deployment file not found: $NGINX_DEPLOYMENT"
        exit 1
    fi
fi

# Fetch certificates from Azure Key Vault
log_info "Fetching TLS certificate from Azure Key Vault..."

TLS_CRT=$(az keyvault secret show --vault-name "$VAULT_NAME" --name "IDPBUILDER-TLS-CRT" --query value -o tsv)
TLS_KEY=$(az keyvault secret show --vault-name "$VAULT_NAME" --name "IDPBUILDER-TLS-KEY" --query value -o tsv)

if [ -z "$TLS_CRT" ] || [ -z "$TLS_KEY" ]; then
    log_error "Failed to fetch TLS certificate or key from Key Vault"
    exit 1
fi

log_success "TLS certificate fetched from Key Vault"

# Verify static deployment file exists
if [ ! -f "$NGINX_DEPLOYMENT" ]; then
    log_error "Static nginx deployment file not found: $NGINX_DEPLOYMENT"
    exit 1
fi

# Generate combined override file: Secret (dynamic) + Deployment (static from git)
log_info "Generating nginx override: Secret (from AKV) + Deployment (from git)..."

cat > "$OUTPUT_FILE" <<'YAML_HEADER'
# Auto-generated nginx override with persistent TLS certificate
# Generated by: generate-nginx-override.sh
#
# Architecture:
#   - Secret: Generated from Azure Key Vault (dynamic, not in git)
#   - Deployment: From deployment/overrides/nginx-hostnetwork-no-hostport.yaml (static, in git)
#   - ExternalSecret: packages/base/manifests/nginx-tls-secret/ manages ongoing updates via ESO
#
# Do not edit - regenerate by running the script again
---
apiVersion: v1
kind: Secret
metadata:
  name: persistent-tls-cert
  namespace: ingress-nginx
  labels:
    app.kubernetes.io/name: persistent-tls-cert
    app.kubernetes.io/part-of: idpbuilder
type: kubernetes.io/tls
data:
YAML_HEADER

# Add certificate data (already base64 encoded from AKV)
echo "  tls.crt: ${TLS_CRT}" >> "$OUTPUT_FILE"
echo "  tls.key: ${TLS_KEY}" >> "$OUTPUT_FILE"

# Append the static deployment from git (no secrets in this file)
echo "---" >> "$OUTPUT_FILE"
cat "$NGINX_DEPLOYMENT" >> "$OUTPUT_FILE"

log_success "Generated nginx override: $OUTPUT_FILE"
log_info "  Secret: from Azure Key Vault (dynamic)"
log_info "  Deployment: from $NGINX_DEPLOYMENT (static, version-controlled)"

# Also generate ArgoCD override with CA trust ConfigMap AND performance tuning
# This allows ArgoCD repo-server to connect to Gitea over HTTPS with our custom cert
# Performance tuning enables faster sync for 128+ applications
ARGOCD_OVERRIDE_FILE="/tmp/argocd-override-with-ca.yaml"

log_info "Generating ArgoCD override with CA trust and performance tuning..."

# Fetch CA certificate
CA_CRT=$(az keyvault secret show --vault-name "$VAULT_NAME" --name "IDPBUILDER-CA-CRT" --query value -o tsv | base64 -d)

if [ -n "$CA_CRT" ]; then
    cat > "$ARGOCD_OVERRIDE_FILE" <<EOF
# Auto-generated ArgoCD override with persistent CA trust and performance tuning
# Generated by: generate-nginx-override.sh
# Do not edit - regenerate by running the script again
---
# Performance tuning for ArgoCD controller
# Optimized for syncing 128+ applications quickly
apiVersion: v1
kind: ConfigMap
metadata:
  name: argocd-cmd-params-cm
  namespace: argocd
  labels:
    app.kubernetes.io/name: argocd-cmd-params-cm
    app.kubernetes.io/part-of: argocd
data:
  # Status processors: concurrent status update goroutines (default: 20)
  controller.status.processors: "50"
  # Operation processors: concurrent sync operations (default: 10)
  controller.operation.processors: "25"
  # Kubectl parallelism: concurrent kubectl commands (default: 20)
  controller.kubectl.parallelism.limit: "30"
  # Use server-side diff for more accurate comparison
  controller.diff.server.side: "true"
  # Repo server parallelism: concurrent manifest generation
  reposerver.parallelism.limit: "50"
---
# CA trust for Gitea HTTPS connections
apiVersion: v1
kind: ConfigMap
metadata:
  name: argocd-tls-certs-cm
  namespace: argocd
  labels:
    app.kubernetes.io/name: argocd-tls-certs-cm
    app.kubernetes.io/part-of: argocd
data:
  gitea.cnoe.localtest.me: |
$(echo "$CA_CRT" | sed 's/^/    /')
  cnoe.localtest.me: |
$(echo "$CA_CRT" | sed 's/^/    /')
EOF
    log_success "Generated ArgoCD override: $ARGOCD_OVERRIDE_FILE (CA trust + performance tuning)"
else
    log_warning "Could not fetch CA certificate for ArgoCD trust"
fi

# Output the file path for use in scripts
echo "$OUTPUT_FILE"
