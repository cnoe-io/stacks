class MockClaudeAgent:
    """Mock Claude agent for E2E testing."""

    def __init__(self, agent_name: str, mock_response: str = None):
        self.agent_name = agent_name
        self.mock_response = mock_response or f"Generated by {agent_name}"
        self.invocations: list[dict] = []

    async def process_task(
        self, task: str, context: dict[str, Any], trace_ctx: TraceContext = None
    ) -> dict[str, Any]:
        """Process a task and return result."""
        self.invocations.append({
            "task": task,
            "context": context,
            "trace_ctx": trace_ctx,
            "timestamp": datetime.utcnow(),
        })

        return {
            "result": self.mock_response,
            "artifact_content": f"# {self.agent_name.title()} Output\n\n{self.mock_response}",
            "duration_ms": 1000,
            "tokens_used": {"input": 500, "output": 200},
        }


class MockWorkflowOrchestrator:
    """Mock workflow orchestrator for E2E testing."""

    def __init__(self, agents: dict[str, MockClaudeAgent]):
        self.agents = agents
        self.workflows: dict[UUID, Workflow] = {}
        self.phase_transitions: list[dict] = []

    async def start_workflow(
        self, feature_description: str, trace_id: str = None
    ) -> Workflow:
        """Start a new workflow."""
        workflow = Workflow(
            id=uuid4(),
            feature_description=feature_description,
            status=WorkflowStatus.PENDING,
            current_phase=WorkflowPhase.SPECIFICATION,
        )
        self.workflows[workflow.id] = workflow
        return workflow

    async def execute_phase(
        self, workflow_id: UUID, phase: WorkflowPhase
    ) -> dict[str, Any]:
        """Execute a specific phase."""
        workflow = self.workflows.get(workflow_id)
        if not workflow:
            raise ValueError(f"Workflow {workflow_id} not found")

        agent_map = {
            WorkflowPhase.SPECIFICATION: "specifier",
            WorkflowPhase.PLANNING: "planner",
            WorkflowPhase.TASK_GENERATION: "taskgenerator",
            WorkflowPhase.IMPLEMENTATION: "implementer",
        }

        agent_name = agent_map.get(phase)
        agent = self.agents.get(agent_name)
        if not agent:
            raise ValueError(f"No agent for phase {phase}")

        # Update workflow status
        workflow.status = WorkflowStatus.IN_PROGRESS
        workflow.current_phase = phase
        workflow.current_agent = agent_name

        # Execute task
        result = await agent.process_task(
            task=f"execute_{phase.value}",
            context={"workflow_id": str(workflow_id)},
        )

        # Record transition
        self.phase_transitions.append({
            "workflow_id": workflow_id,
            "phase": phase,
            "agent": agent_name,
            "result": result,
            "timestamp": datetime.utcnow(),
        })

        return result

    async def complete_workflow(self, workflow_id: UUID) -> Workflow:
        """Mark workflow as complete."""
        workflow = self.workflows.get(workflow_id)
        if workflow:
            workflow.status = WorkflowStatus.COMPLETED
            workflow.completed_at = datetime.utcnow()
        return workflow


class TestFullWorkflowExecution:
    """E2E tests for complete workflow execution."""

    @pytest.fixture
    def mock_agents(self):
        """Create mock agents for all phases."""
        return {
            "specifier": MockClaudeAgent(
                "specifier",
                "Feature specification with acceptance criteria"
            ),
            "planner": MockClaudeAgent(
                "planner",
                "Implementation plan with architecture decisions"
            ),
            "taskgenerator": MockClaudeAgent(
                "taskgenerator",
                "Task breakdown with dependencies"
            ),
            "implementer": MockClaudeAgent(
                "implementer",
                "Code implementation with tests"
            ),
        }

    @pytest.fixture
    def orchestrator(self, mock_agents):
        """Create orchestrator with mock agents."""
        return MockWorkflowOrchestrator(mock_agents)

    @pytest.mark.asyncio
    async def test_workflow_completes_all_phases(self, orchestrator):
        """Workflow should complete all phases successfully."""
        # Start workflow
        workflow = await orchestrator.start_workflow(
            feature_description="Add user authentication with OAuth2"
        )
        assert workflow.status == WorkflowStatus.PENDING

        # Execute all phases
        phases = [
            WorkflowPhase.SPECIFICATION,
            WorkflowPhase.PLANNING,
            WorkflowPhase.TASK_GENERATION,
            WorkflowPhase.IMPLEMENTATION,
        ]

        for phase in phases:
            result = await orchestrator.execute_phase(workflow.id, phase)
            assert result["result"] is not None
            assert result["tokens_used"]["input"] > 0

        # Complete workflow
        completed = await orchestrator.complete_workflow(workflow.id)
        assert completed.status == WorkflowStatus.COMPLETED
        assert completed.completed_at is not None

    @pytest.mark.asyncio
    async def test_all_agents_invoked_in_order(self, orchestrator, mock_agents):
        """All agents should be invoked in correct order."""
        workflow = await orchestrator.start_workflow("Test feature")

        phases = [
            WorkflowPhase.SPECIFICATION,
            WorkflowPhase.PLANNING,
            WorkflowPhase.TASK_GENERATION,
            WorkflowPhase.IMPLEMENTATION,
        ]

        for phase in phases:
            await orchestrator.execute_phase(workflow.id, phase)

        # Verify agent invocations
        expected_agents = ["specifier", "planner", "taskgenerator", "implementer"]
        for i, transition in enumerate(orchestrator.phase_transitions):
            assert transition["agent"] == expected_agents[i]

    @pytest.mark.asyncio
    async def test_workflow_tracks_phase_transitions(self, orchestrator):
        """Workflow should track all phase transitions."""
        workflow = await orchestrator.start_workflow("Test feature")

        await orchestrator.execute_phase(workflow.id, WorkflowPhase.SPECIFICATION)
        await orchestrator.execute_phase(workflow.id, WorkflowPhase.PLANNING)

        transitions = orchestrator.phase_transitions
        assert len(transitions) == 2
        assert transitions[0]["phase"] == WorkflowPhase.SPECIFICATION
        assert transitions[1]["phase"] == WorkflowPhase.PLANNING

    @pytest.mark.asyncio
    async def test_workflow_preserves_context_across_phases(
        self, orchestrator, mock_agents
    ):
        """Context should be preserved across phase transitions."""
        workflow = await orchestrator.start_workflow("Add caching layer")

        # Execute all phases
        for phase in [
            WorkflowPhase.SPECIFICATION,
            WorkflowPhase.PLANNING,
            WorkflowPhase.TASK_GENERATION,
            WorkflowPhase.IMPLEMENTATION,
        ]:
            await orchestrator.execute_phase(workflow.id, phase)

        # All agents should have received workflow_id in context
        for agent in mock_agents.values():
            assert len(agent.invocations) == 1
            assert "workflow_id" in agent.invocations[0]["context"]


